"""LLM 답변 후처리.

프롬프트로 최대한 막더라도, 모델은 종종 딱딱한 표현이나 과한 단정 문구를 남깁니다.
이 단계는 모델 출력을 뒤엎기보다, 자주 발생하는 어색한 표현만 얕게 정리합니다.
"""

import re


ANSWER_REPLACEMENTS = {
    "제공된 상품 후보 중에서는 ": "",
    "제공된 상품 후보들 중에서는 ": "지금 후보들 중에서는 ",
    "제공된 상품 후보들 중에서 ": "지금 후보들 중에서는 ",
    "제공된 상품 후보들에는 ": "지금 후보들에는 ",
    "제공된 후보 중에서는 ": "지금 후보들 중에서는 ",
    "제공된 후보들 중에서는 ": "지금 후보들 중에서는 ",
    "제공된 후보들 중에서 ": "지금 후보들 중에서는 ",
    "제공된 후보들에는 ": "지금 후보들에는 ",
    "특정하기 어렵습니다.": "바로 하나로 좁히기는 어렵습니다.",
    "특정하기 어렵습니다": "바로 하나로 좁히기는 어렵습니다",
    "향료와 알코올이 없는 제품을 찾으시는군요.": "향료와 알코올은 피하는 쪽으로 보고 계시군요.",
    "향료와 에센셜 오일을 제외한 제품을 찾으신다면,": "향료와 에센셜 오일은 피하는 쪽으로 본다면,",
    "향료와 에센셜 오일을 제외한 제품으로 찾아보는 것이 좋겠어요.": "향료와 에센셜 오일은 피하는 쪽으로 보는 게 좋겠어요.",
    "향료와 알코올이 없는 제품을 찾고 계시군요.": "향료와 알코올은 피하는 쪽으로 보고 계시군요.",
    "알코올이 강한 제품을 피하고 싶으시군요.": "알코올 부담은 낮추고 싶은 쪽이시군요.",
    "향료, 알코올, 오일 성분을 피하면서 ": "향료, 알코올, 오일 성분까지 함께 고려해서 ",
    "향료와 에센셜 오일은 피하는 방향으로 고려해 볼 수 있어요.": "향료와 에센셜 오일까지 함께 고려해서 후보를 좁혀볼 수 있어요.",
    "배제하고 ": "함께 고려해서 ",
    "제외한 제품": "그 조건을 함께 고려한 후보",
}


def postprocess_answer(answer: str) -> str:
    """최종 응답 문장을 가볍게 정리합니다.

    규칙은 보수적으로 유지합니다.
    너무 공격적으로 치환하면 문맥이 망가질 수 있어서,
    실제로 반복적으로 튀는 표현만 교정 대상으로 둡니다.
    """
    cleaned = answer.strip()
    for before, after in ANSWER_REPLACEMENTS.items():
        cleaned = cleaned.replace(before, after)
    return re.sub(r"\s+", " ", cleaned).strip()
